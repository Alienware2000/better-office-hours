  const request=(route,value,headers={})=>fetch(origin+route,value===undefined?{headers}:{method:'POST',headers:{Origin:origin,'Content-Type':'application/json','X-Review-Token':token,...headers},body:JSON.stringify(value)});
  let state=await (await request('/api/state')).json(),token=state.csrf;
  assert.equal(state.reports.length,1);assert.equal(calls,0,'Loading UI never starts inference');
  const id=state.reports[0].id;
  const page=await (await request(`/api/report?id=${id}`)).json();
  assert.ok(page.rendering.pages[0].svg.includes('data-board-group="object"'));
  assert.deepEqual(page.inputMessages,input.messages);
  for(const asset of ['/','/review.css','/review.js','/board.css','/board-playback.js','/speech.js'])assert.equal((await request(asset)).status,200);
  assert.equal((await request('/.env.benchmark.local')).status,404);
  assert.equal((await request('/api/state',undefined,{Origin:'https://outside.example'})).status,403);
  assert.equal((await request('/api/run',{},{'X-Review-Token':'wrong'})).status,403);
  const batch={models:['anthropic/claude-opus-5','openai/gpt-6-astra'],cases:cases.map(c=>c.id),repeats:3};
  assert.equal((await request('/api/run',batch)).status,400);assert.equal(calls,0);
  const rating={id,correctness:'pass',teaching:'concern',visuals:'unrated',notes:'Synthetic persistence check only'};
  assert.equal((await request('/api/rating',rating)).status,200);
  assert.equal(fs.statSync(path.join(dir,'review/ratings.json')).mode&0o777,0o600);
  app.stop();await new Promise(resolve=>app.server.once('close',resolve));
  app=createReviewServer({dataRoot:dir,port:0,generate});port=await app.start();origin=`http://127.0.0.1:${port}`;
  state=await (await request('/api/state')).json();token=state.csrf;
  assert.equal(state.reports[0].rating.notes,rating.notes);
  assert.equal((await request('/api/run',{models:batch.models,cases:[cases[0].id],repeats:1})).status,202);
  for(let i=0;i<40&&!release;i++)await new Promise(r=>setTimeout(r,10));
  assert.equal(calls,1);state=await (await request('/api/state')).json();assert.equal(state.job.current.progress.speech,'Live synthetic progress');
  assert.ok((await (await request('/api/live-board')).json()).svg.includes('data-board-group="object"'));
  assert.equal((await request('/api/run',{models:batch.models,cases:[cases[0].id],repeats:1})).status,409);
  assert.equal((await request('/api/cancel',{})).status,200);
  for(let i=0;i<40;i++){state=await(await request('/api/state')).json();if(state.job.state!=='running')break;await new Promise(r=>setTimeout(r,10));}
  assert.equal(state.job.state,'cancelled');assert.equal(calls,1,'Cancellation prevents next request');assert.equal(state.reports.length,2);
  assert.ok(renderReview({...result,appParsed:false,rawContent:'```json\n{}\n```'}).error);
  const revealView=renderReview(result,'1',0,true);
  assert.ok(revealView.pages[0].reveals[0].svg.includes('is-entering'));
  assert.ok(revealView.pages[0].reveals[0].duration>=520);
  assert.equal(renderReview(result).pages[0].reveals,undefined,'Static inspectors stay static');
