// Isolated review-server integration checks. No credentials or external API calls.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createReviewServer, readReports } from './review-tutor-models.mjs';
import { renderReview, renderAcceptedBoard } from './evaluation/render.mjs';
import { createHarness, cases } from './bench-tutor-models.mjs';
const dir=fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()),'boh-review-test-'));
const harness=createHarness(), input=await harness.request(cases[0]);
const lesson={handoff:false,move:'explain',visual:'diagram',introduction:'Observe the circle.',beats:[{pdf:'',draw:[JSON.stringify({op:'circle',id:'object',center:{x:.4,y:.4},r:.1})],animation:'',speech:'The circle represents an object.'}],question:''};
const result={case:cases[0].id,modelRequested:'anthropic/claude-opus-5',appParsed:true,rawContent:JSON.stringify(lesson),speech:'Observe the circle.',board:{commands:[{op:'circle',id:'object',center:{x:.4,y:.4},r:.1}]},firstContentMs:10,firstSpeechReadyMs:20,firstBoardReadyMs:30,totalMs:50,events:[]};
const report={kind:'live-synthetic-teaching-benchmark',generatedAt:new Date().toISOString(),effort:'low',requests:[{case:cases[0].id,maxTokens:8000,inputSha256:createHash('sha256').update(JSON.stringify(input.messages)).digest('hex')}],results:[result]};
fs.writeFileSync(path.join(dir,'fixture.json'),JSON.stringify(report));
fs.writeFileSync(path.join(dir,'unrelated.json'),JSON.stringify({secret:'must-not-serve'}));
fs.symlinkSync(path.join(dir,'fixture.json'),path.join(dir,'linked.json'));
let calls=0, release;
const generate=async(request,fixture,progress,signal)=>{calls++;progress({speech:'Live synthetic progress',board:result.board,firstSpeechReadyMs:20,firstBoardReadyMs:30});await new Promise(resolve=>{release=resolve;signal.addEventListener('abort',resolve,{once:true});});return {...result,case:fixture.id,modelRequested:request.model};};
let app=createReviewServer({dataRoot:dir,port:0,generate});
try {
  let port=await app.start(),origin=`http://127.0.0.1:${port}`;
  const request=(route,value,headers={})=>fetch(origin+route,value===undefined?{headers}:{method:'POST',headers:{Origin:origin,'Content-Type':'application/json','X-Review-Token':token,...headers},body:JSON.stringify(value)});
  let state=await (await request('/api/state')).json(),token=state.csrf;
  assert.equal(state.reports.length,1);assert.equal(calls,0,'Loading UI never starts inference');
  const id=state.reports[0].id;
  const page=await (await request(`/api/report?id=${id}`)).json();
  assert.ok(page.rendering.pages[0].svg.includes('data-board-group="object"'));
  assert.deepEqual(page.inputMessages,input.messages);
  for(const asset of ['/','/review.css','/review.js','/board.css'])assert.equal((await request(asset)).status,200);
  assert.equal((await request('/.env.benchmark.local')).status,404);
  assert.equal((await request('/api/state',undefined,{Origin:'https://outside.example'})).status,403);
  assert.equal((await request('/api/run',{},{'X-Review-Token':'wrong'})).status,403);
  const batch={models:['anthropic/claude-opus-5','openai/gpt-6-astra'],cases:cases.map(c=>c.id),repeats:3};
  assert.equal((await request('/api/run',batch)).status,400);assert.equal(calls,0);
  const rating={id,correctness:'pass',teaching:'concern',visuals:'unrated',notes:'Synthetic persistence check only'};
  assert.equal((await request('/api/rating',rating)).status,200);
  assert.equal(fs.statSync(path.join(dir,'review/ratings.json')).mode&0o777,0o600);
  app.stop();await new Promise(resolve=>app.server.once('close',resolve));
  app=createReviewServer({dataRoot:dir,port:0,generate});port=await app.start();origin=`http://127.0.0.1:${port}`;
  state=await (await request('/api/state')).json();token=state.csrf;
  assert.equal(state.reports[0].rating.notes,rating.notes);
  assert.equal((await request('/api/run',{models:batch.models,cases:[cases[0].id],repeats:1})).status,202);
  for(let i=0;i<40&&!release;i++)await new Promise(r=>setTimeout(r,10));
  assert.equal(calls,1);state=await (await request('/api/state')).json();assert.equal(state.job.current.progress.speech,'Live synthetic progress');
  assert.ok((await (await request('/api/live-board')).json()).svg.includes('data-board-group="object"'));
  assert.equal((await request('/api/run',{models:batch.models,cases:[cases[0].id],repeats:1})).status,409);
  assert.equal((await request('/api/cancel',{})).status,200);
  for(let i=0;i<40;i++){state=await(await request('/api/state')).json();if(state.job.state!=='running')break;await new Promise(r=>setTimeout(r,10));}
  assert.equal(state.job.state,'cancelled');assert.equal(calls,1,'Cancellation prevents next request');assert.equal(state.reports.length,2);
  assert.ok(renderReview({...result,appParsed:false,rawContent:'```json\n{}\n```'}).error);
  const clipped={...lesson,beats:[{...lesson.beats[0],draw:Array.from({length:7},(_,i)=>JSON.stringify({op:'circle',id:`object${i}`,center:{x:.4,y:.4},r:.01}))},{...lesson.beats[0],draw:[JSON.stringify({op:'highlight',id:'object6'})]}]};
  const view=renderReview({...result,rawContent:JSON.stringify(clipped)});
  assert.ok(view.warnings.some(w=>w.includes('only the first six')));
  assert.ok(view.warnings.some(w=>w.includes('missing object "object6"')));
  const animation={id:'new-scene',duration:1,shapes:[{id:'new-dot',kind:'dot',keyframes:[{t:0,at:{x:.3,y:.3},r:.01},{t:1,at:{x:.6,y:.3},r:.01}]}]};
  const arrow={op:'arrow',id:'later-arrow',from:{x:.2,y:.8},to:{x:.6,y:.8}};
  const ordered=renderAcceptedBoard(cases[0].id,null,[{board:result.board},{board:{...result.board,animation}},{board:{commands:[...result.board.commands,arrow],animation}}]);
  assert.ok(ordered.includes('data-board-group="later-arrow"'));
  assert.ok(!ordered.includes('data-board-group="object"'),'Live reconstruction preserves new-page ordering rather than combining all commands before animation');
  assert.equal(readReports(dir).length,2);
  console.log('PASS: report isolation, actual board rendering, raw failures, clipped-target diagnostics, same-origin/token controls, request limits, rating persistence, live progress, cancellation, and no automatic API calls.');
} finally {app.stop();fs.rmSync(dir,{recursive:true,force:true});}
